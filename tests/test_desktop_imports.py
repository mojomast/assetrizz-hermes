from __future__ import annotations

import re
from pathlib import Path

PLUGIN_JS = Path(__file__).resolve().parents[1] / "desktop" / "plugin.js"
ALLOWED = {"@hermes/plugin-sdk", "react", "react/jsx-runtime"}


def test_desktop_plugin_only_imports_sdk_and_react():
    text = PLUGIN_JS.read_text(encoding="utf-8")
    imports = re.findall(r"from\s+[\"']([^\"']+)[\"']", text)
    assert imports, "plugin.js should import the Desktop SDK"
    assert set(imports) <= ALLOWED
    assert "eval(" not in text
    assert "new Function" not in text
    # Must not attach grants or dial loopback from the iframe.
    assert "Authorization" not in text
    assert "127.0.0.1" not in text
    assert "localhost" not in text


def test_bundle_is_generated():
    text = PLUGIN_JS.read_text(encoding="utf-8")
    assert text.startswith("// Generated by plugin/desktop/build_plugin.py")
    assert "const PANE_CSS" in text
    assert "function mountPane" in text
    assert "registerComposer" in text
